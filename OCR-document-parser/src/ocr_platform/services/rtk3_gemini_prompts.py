def build_gemini_prompt(requested: set[str], *, full_claims: bool) -> str:
    """Build only the instructions relevant to the actual response schema."""
    sections = [COMMON]
    for name, rule in SCALAR_RULES.items():
        if name in requested:
            sections.append(f"Поле {name}: {rule}")
    if full_claims:
        sections.append(AWARD_BALANCE)
        sections.append(FULL_FORMAT)
        sections.extend(f"Поле claims[].{name}: {rule}" for name, rule in CLAIM_RULES.items())
    elif any(name.startswith("claim_") for name in requested):
        if any(name.endswith("_included_total") for name in requested):
            sections.append(AWARD_BALANCE)
        sections.append(FIXED_FORMAT)
        for key in sorted(requested):
            match = re.fullmatch(r"claim_[1-9][0-9]*_(.+)", key)
            if not match:
                continue
            name = match[1]
            sections.append(f"Поле {key}: {CLAIM_RULES[name]}\n" +
                            FIXED_FIELD_FORMATS.get(name, COMPONENT_FORMAT))
    sections.append(COMPUTED)
    return "\n\n".join(sections)
